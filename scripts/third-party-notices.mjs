// Builds public/THIRD_PARTY_NOTICES.txt: the licence text of every npm package
// whose code or files end up inside the shipped app.
//
// MIT, Apache-2.0 and OFL all require their notices to travel with copies of
// the software, and the minified bundle strips them, so this file carries them
// instead. It ships in dist/ and is shown in the app's About dialog.
//
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 if the file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = path.join(ROOT, 'public', 'THIRD_PARTY_NOTICES.txt');
const FIRMWARE_INFO = path.join(ROOT, 'public', 'firmware', 'micropython.json');
const FIRMWARE_LICENSE = path.join(ROOT, 'firmware', 'micropython', 'LICENSE');

// Packages imported by src/ (the roots of what Vite bundles). Their runtime
// `dependencies` are followed automatically. Add a package here when src/
// starts importing it; tests/notices.test.ts fails until you do.
export const BUNDLED_ROOTS = [
  'blockly',
  '@blockly/field-colour',
  'react',
  'react-dom',
  'codemirror',
  '@codemirror/commands',
  '@codemirror/lang-python',
  '@codemirror/language',
  '@codemirror/state',
  '@codemirror/view',
  '@fontsource-variable/fredoka',
];

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

function findPackageDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (dir === path.dirname(dir)) throw new Error(`Cannot find package ${name} (needed from ${fromDir})`);
  }
}

export function collectPackages() {
  const seen = new Map();
  const visit = (name, fromDir) => {
    const dir = findPackageDir(name, fromDir);
    if (seen.has(dir)) return;
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    seen.set(dir, { dir, pkg });
    for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
  };
  for (const name of BUNDLED_ROOTS) visit(name, ROOT);
  return [...seen.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name) || a.pkg.version.localeCompare(b.pkg.version));
}

function repoUrl(pkg) {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return r ? r.replace(/^git\+/, '').replace(/\.git$/, '') : pkg.homepage ?? '';
}

export function buildNotices() {
  const packages = collectPackages();
  const missing = [];
  const rule = '='.repeat(78);
  const parts = [
    'Eaglets Code: third-party software notices',
    '',
    'Eaglets Code includes the open-source software listed below. Each package is',
    'used under its own licence, reproduced in full. This file is generated by',
    'scripts/third-party-notices.mjs; do not edit it by hand.',
    '',
    'The desktop app is also built on Electron and Chromium. Their licences are in',
    'LICENSE.electron.txt and LICENSES.chromium.html next to the app.',
    '',
    'Packages:',
    ...packages.map(({ pkg }) => `  ${pkg.name} ${pkg.version} (${pkg.license ?? 'see below'})`),
    '',
  ];
  for (const { dir, pkg } of packages) {
    const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile()).sort();
    if (files.length === 0) missing.push(`${pkg.name}@${pkg.version}`);
    parts.push(rule, `${pkg.name} ${pkg.version}`, `License: ${pkg.license ?? 'UNKNOWN'}`);
    const url = repoUrl(pkg);
    if (url) parts.push(`Source: ${url}`);
    parts.push(rule, '');
    for (const f of files) parts.push(fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim(), '');
  }
  // The MicroPython firmware the app can install onto the robot (scripts/fetch-micropython.mjs).
  if (fs.existsSync(FIRMWARE_INFO) && fs.existsSync(FIRMWARE_LICENSE)) {
    const fw = JSON.parse(fs.readFileSync(FIRMWARE_INFO, 'utf8'));
    const builds = fw.builds ?? [fw];
    parts.push(
      rule,
      `MicroPython ${fw.version} firmware (${builds.map((b) => b.file).join(', ')})`,
      'License: MIT, with the bundled components listed below',
      `Source: https://github.com/micropython/micropython/tree/v${fw.version}`,
      rule,
      '',
      fs.readFileSync(FIRMWARE_LICENSE, 'utf8').replace(/\r\n/g, '\n').trim(),
      '',
    );
  } else if (fs.existsSync(FIRMWARE_INFO)) {
    missing.push('MicroPython firmware (firmware/micropython/LICENSE)');
  }
  return { text: parts.join('\n'), packages, missing };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, packages, missing } = buildNotices();
  if (missing.length) {
    console.error(`No licence file found for: ${missing.join(', ')}. Add its licence text by hand before shipping.`);
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== text) {
      console.error('public/THIRD_PARTY_NOTICES.txt is out of date. Run: npm run notices');
      process.exit(1);
    }
    console.log(`Third-party notices up to date (${packages.length} packages).`);
  } else {
    fs.writeFileSync(OUTPUT, text);
    console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${packages.length} packages).`);
  }
}
